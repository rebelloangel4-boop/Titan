 for i,line in enumerate(textwrap.wrap(title.upper(),17)[:6]):text(line,250+i*35,3,(235,242,255))
 text('LOCAL RENDER',540,3,(130,160,190))
 return f'P6\n{w} {h}\n255\n'.encode()+data
