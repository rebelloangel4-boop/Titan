def title_frame(title,w,h):
 data=bytearray()
 for y in range(h):
  for x in range(w):data.extend((10+int(10*y/h),18+int(20*x/w),32+int(25*y/h)))
 def text(line,y,scale,color):
  start=(w-len(line)*6*scale)//2
  for n,ch in enumerate(line):
   for row,bits in enumerate(FONT.get(ch,FONT['-'])):
    for col,on in enumerate(bits):
     if on=='1':
      for dy in range(scale):
       for dx in range(scale):
        x=start+n*6*scale+col*scale+dx;yy=y+row*scale+dy
        if 0<=x<w and 0<=yy<h:data[(yy*w+x)*3:(yy*w+x)*3+3]=bytes(color)
